-- ============================================================

-- 1. Reports Table
CREATE TABLE IF NOT EXISTS public.reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seed_id TEXT UNIQUE,
    tracking_token TEXT UNIQUE NOT NULL,
    description TEXT NOT NULL,
    citizen_category TEXT,
    predicted_category TEXT,
    category_evidence TEXT,
    extractive_summary TEXT,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    area TEXT NOT NULL,
    priority_score INTEGER NOT NULL,
    priority_label TEXT NOT NULL,
    priority_reasons TEXT,
    priority_override_score INTEGER,
    priority_override_label TEXT,
    priority_override_reason TEXT,
    needs_review INTEGER NOT NULL DEFAULT 0,
    analysis_status TEXT NOT NULL DEFAULT 'pending',
    analysis_error TEXT,
    workflow_status TEXT NOT NULL DEFAULT 'Submitted',
    assigned_department TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc', NOW()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc', NOW())
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_reports_tracking_token ON public.reports(tracking_token);
CREATE INDEX IF NOT EXISTS idx_reports_area ON public.reports(area);
CREATE INDEX IF NOT EXISTS idx_reports_workflow_status ON public.reports(workflow_status);
CREATE INDEX IF NOT EXISTS idx_reports_priority_score ON public.reports(priority_score DESC);

-- 2. Status Events (Audit Trail)
CREATE TABLE IF NOT EXISTS public.status_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    previous_value TEXT,
    new_value TEXT,
    note TEXT,
    is_public INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_status_events_report_id ON public.status_events(report_id);
CREATE INDEX IF NOT EXISTS idx_status_events_created_at ON public.status_events(created_at);

-- 3. Duplicate Relationships
CREATE TABLE IF NOT EXISTS public.duplicate_relationships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_report_id BIGINT NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
    candidate_report_id BIGINT NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
    similarity_score DOUBLE PRECISION NOT NULL,
    distance_meters DOUBLE PRECISION NOT NULL,
    review_state TEXT NOT NULL DEFAULT 'suggested',
    created_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc', NOW()),
    CONSTRAINT check_no_self_link CHECK (source_report_id <> candidate_report_id),
    CONSTRAINT unique_duplicate_pair UNIQUE (source_report_id, candidate_report_id)
);

CREATE INDEX IF NOT EXISTS idx_dup_source ON public.duplicate_relationships(source_report_id);
CREATE INDEX IF NOT EXISTS idx_dup_candidate ON public.duplicate_relationships(candidate_report_id);

-- Enable Row Level Security (RLS) if desired (public read/insert enabled by default)
ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.status_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.duplicate_relationships ENABLE ROW LEVEL SECURITY;

-- Allow anonymous access for the hackathon demo
CREATE POLICY "Public Read Access" ON public.reports FOR SELECT USING (true);
CREATE POLICY "Public Insert Access" ON public.reports FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Update Access" ON public.reports FOR UPDATE USING (true);

CREATE POLICY "Public Read Events" ON public.status_events FOR SELECT USING (true);
CREATE POLICY "Public Insert Events" ON public.status_events FOR INSERT WITH CHECK (true);

CREATE POLICY "Public Read Duplicates" ON public.duplicate_relationships FOR SELECT USING (true);
CREATE POLICY "Public Insert Duplicates" ON public.duplicate_relationships FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Update Duplicates" ON public.duplicate_relationships FOR UPDATE USING (true);
